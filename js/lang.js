  let language = 'uk';
  try { if (localStorage.getItem('smakhub-language') === 'en') language = 'en'; } catch {}

  function english(value) {
    if (Object.hasOwn(messages, value)) return messages[value];
    const patterns = [
      [/^Рецепти (\d+–\d+)$/, "Recipes $1"],
      [/^(\d+) хв · (.+)$/, (_,n,level)=>n+" min · "+english(level)],
      [/^Знайдено рецептів: (\d+) із (\d+)$/, 'Recipes found: $1 of $2'],
      [/^Збережено рецептів: (\d+)$/, 'Saved recipes: $1'],
      [/^Вітаємо, (.*)!$/, 'Welcome, $1!'],
      [/^(\d+) хв$/, '$1 min'],
      [/^Час: (\d+) хв$/, 'Time: $1 min'],
      [/^Група (.+)$/, 'Group $1'],
      [/^Видалити зі збережених: (.+)$/, (_, name) => 'Remove from saved: ' + english(name)],
      [/^(.+) — SmakHub$/, (_, name) => english(name) + ' — SmakHub']
    ];
    for (const [rx, replacement] of patterns) {
      if (rx.test(value)) return value.replace(rx, replacement);
    }
    return value;
  }

  function translateValue(node, key, value, write) {
    const fields = originals.get(node) || new Map();
    const previous = fields.get(key);
    const source = previous && previous.rendered === value ? previous.source : value;
    const translated = language === 'en'
      ? source.replace(/^(\s*)([\s\S]*?)(\s*)$/, (_, before, copy, after) => before + english(copy) + after)
      : source;
    if (translated !== value) write(translated);
    fields.set(key, { source, rendered: translated });
    originals.set(node, fields);
  }

  function render(node) {
    if (node.nodeType === Node.TEXT_NODE) {
      translateValue(node, 'text', node.data, value => { node.data = value; });
      return;
    }
    if (node.nodeType !== Node.ELEMENT_NODE || node.matches('script,style,textarea,code,[translate="no"]')) return;
    for (const attribute of attributes) {
      if (node.hasAttribute(attribute)) {
        translateValue(node, attribute, node.getAttribute(attribute), value => node.setAttribute(attribute, value));
      }
    }
    for (const child of node.childNodes) render(child);
  }

  function mount() {
    const wrapper = document.querySelector('footer .footer-inner') || document.querySelector('footer');
    const switcher = document.createElement('button');
    switcher.type = 'button';
    switcher.className = 'btn btn-outline language-switch';
    switcher.setAttribute('translate', 'no');
    wrapper?.append(switcher);
    const observer = new MutationObserver(records => {
      observer.disconnect();
      for (const record of records) {
        const parent = record.target.nodeType === Node.ELEMENT_NODE ? record.target : record.target.parentElement;
        if (parent?.closest('script, style, textarea, code, [translate="no"]')) continue;
        if (record.type === 'childList') record.addedNodes.forEach(render);
        else render(record.target);
      }
      observe();
    });
    function observe() {
      observer.observe(document.documentElement, {
        subtree: true, characterData: true, childList: true, attributes: true, attributeFilter: attributes
      });
    }
    function applyLanguage() {
      observer.disconnect();
      document.documentElement.lang = language;
      switcher.textContent = language === 'uk' ? 'English' : 'Українська';
      switcher.lang = language === 'uk' ? 'en' : 'uk';
      switcher.setAttribute('aria-label', language === 'uk' ? 'Switch to English' : 'Перемкнути на українську');
      render(document.documentElement);
      observe();
      document.dispatchEvent(new CustomEvent('smakhub:language', { detail: language }));
    }
    switcher.addEventListener('click', () => {
      language = language === 'uk' ? 'en' : 'uk';
      try { localStorage.setItem('smakhub-language', language); } catch {}
      applyLanguage();
    });
    applyLanguage();
  }
